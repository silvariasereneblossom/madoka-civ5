-- Phase 6 Lekmod: table rebuild of trait_buildingclassyieldchanges (Kyouko fix)
--------------------------------------------------------------------------------
-- Lekmod v35 implements this table natively -- one of the TRAITIFY convergences
-- -- but names the value column 'Yield integer not null' where Community Patch
-- uses 'YieldChange'. WFTW's SQL/Phase4/Kyouko.sql inserts only (TraitType,
-- BuildingClassType, YieldType, YieldChange); under SQLite 3.7.17 that aborts
-- with 'NOT NULL constraint failed: ...Yield', losing the rest of Kyouko.sql,
-- and NOT NULL cannot be dropped with ALTER TABLE. Instead the table is rebuilt
-- with the identical schema plus DEFAULT 0 on Yield, so WFTW's row loads with
-- Yield = 0 (inert) and the late data patch copies the staged YieldChange into
-- the live Yield. Lekmod's 66 existing rows are copied verbatim. The table has
-- no indexes, triggers, or inbound foreign keys (verified against
-- seed_lekmod35.db), so nothing else needs recreating. Effect-idempotent:
-- re-running on an already-rebuilt table produces the identical schema.
CREATE TABLE "Trait_BuildingClassYieldChanges_rebuild" ("TraitType" text, "BuildingClassType" text references "BuildingClasses"("Type"), "YieldType" text references "Yields"("Type"), "Yield" integer not null default 0);

INSERT INTO "Trait_BuildingClassYieldChanges_rebuild" ("TraitType", "BuildingClassType", "YieldType", "Yield")
SELECT "TraitType", "BuildingClassType", "YieldType", "Yield" FROM "Trait_BuildingClassYieldChanges";

DROP TABLE "Trait_BuildingClassYieldChanges";

ALTER TABLE "Trait_BuildingClassYieldChanges_rebuild" RENAME TO "Trait_BuildingClassYieldChanges";

