#!/usr/bin/env python3
"""Build CvGameCore_Expansion2.dll with clang, using a locally extracted
Windows SDK 7.0 + VC9 tree instead of a system install.

This wraps upstream's build_vp_clang_sdk.py (Community-Patch-DLL) and rewrites
its hard-coded 'C:\\Program Files (x86)\\...' paths to the administrative MSI
extraction under tools/sdk/ext. Nothing is installed system-wide.

Usage:
  python scripts/build_dll.py [--config debug|release] [--repo PATH]
"""
from __future__ import annotations

import argparse
import os
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPO = ROOT / "upstream" / "Community-Patch-DLL"
SDK_EXT = ROOT / "tools" / "sdk" / "ext" / "Program Files"
SDK_DIR = SDK_EXT / "Microsoft SDKs" / "Windows" / "v7.0"
VC9_DIR = SDK_EXT / "Microsoft Visual Studio 9.0" / "Vc7"
# 64-bit LLVM (winget). The toolchain version was not the cause of the 2026-09-18 startup crash; targeting
# the VC9 runtime (-fms-compatibility-version, patch 8 below) was. A 32-bit LLVM runs out of memory linking.
LLVM_BIN = Path(r"C:\Program Files\LLVM\bin")


def write_commit_id(repo: Path) -> None:
    """Mirror update_commit_id.bat: const char CURRENT_GAMECORE_VERSION[] = "<describe> <Clean|Dirty>";"""
    import subprocess

    def git(*a) -> str:
        cp = subprocess.run(["git", *a], cwd=repo, capture_output=True, text=True)
        if cp.returncode != 0:
            raise RuntimeError(f"git {' '.join(a)} failed in {repo}: {cp.stderr.strip()}")
        return cp.stdout.strip()

    dirty = "Dirty" if git("status", "--untracked-files=no", "--porcelain") else "Clean"
    try:
        desc = git("describe", "--tags", "--long", "HEAD")
    except RuntimeError:
        desc = f"No-Tag {git('rev-list', '--abbrev-commit', '-n', '1', 'HEAD')}"
    (repo / "commit_id.inc").write_text(
        f'const char CURRENT_GAMECORE_VERSION[] = "{desc} {dirty}"; //autogenerated, do not commit this file!\n',
        encoding="utf-8")
    print(f"commit id: {desc} {dirty}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="debug", choices=["debug", "release"])
    ap.add_argument("--lto", action="store_true",
                    help="release WITH link-time optimisation (-flto), as upstream does. Off by default: with our LLVM the LTO release DLL fails to initialise in the game (LoadLibrary error 1114, 2026-09-18)")
    ap.add_argument("--repo", default=str(DEFAULT_REPO), help="Community-Patch-DLL checkout (or your fork)")
    ap.add_argument("--llvm-bin", default=os.environ.get("LLVM_BIN", str(LLVM_BIN)),
                    help="folder containing clang-cl.exe and lld-link.exe (env LLVM_BIN)")
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve()
    # PMMM Phase 4: the mod's DLL changes (Ai Yo, Mami's city cap) are applied on top of the checkout.
    # The script is idempotent, so rebuilding an already-patched tree is safe.
    import subprocess
    subprocess.run([sys.executable, str(ROOT / 'scripts' / 'dll_patch_phase4.py'), str(repo)], check=True)
    llvm_bin = Path(args.llvm_bin)
    script = repo / "build_vp_clang_sdk.py"
    for p, what in [(script, "upstream build script"), (SDK_DIR / "Include", "SDK include"),
                    (SDK_DIR / "Lib", "SDK lib"), (VC9_DIR / "include", "VC9 include"),
                    (VC9_DIR / "lib", "VC9 lib"), (llvm_bin / "clang-cl.exe", "clang-cl"),
                    (llvm_bin / "lld-link.exe", "lld-link")]:
        if not p.exists():
            print(f"missing {what}: {p}", file=sys.stderr)
            return 2

    src = script.read_text(encoding="utf-8")
    try:
        patched = patch_upstream(src, repo, llvm_bin, no_lto=not args.lto)
    except PatchError as e:
        print(f"upstream build script changed; refusing to build with a half-applied patch:\n  {e}",
              file=sys.stderr)
        return 3
    write_commit_id(repo)

    tmp = repo / "build_vp_clang_local.py"
    tmp.write_text(patched, encoding="utf-8")

    os.environ["PATH"] = str(llvm_bin) + os.pathsep + os.environ.get("PATH", "")
    saved_cwd, saved_argv = os.getcwd(), sys.argv
    os.chdir(repo)
    sys.argv = [str(tmp), "--config", args.config]
    try:
        runpy.run_path(str(tmp), run_name="__main__")
    except SystemExit as e:
        return e.code if isinstance(e.code, int) else (0 if e.code is None else 1)
    finally:
        os.chdir(saved_cwd)
        sys.argv = saved_argv
    return 0


class PatchError(RuntimeError):
    pass


def _patch(text: str, anchor: str, replacement: str) -> str:
    n = text.count(anchor)
    if n != 1:
        raise PatchError(f"expected exactly one occurrence of {anchor!r}, found {n}")
    return text.replace(anchor, replacement)


def patch_upstream(src: str, repo: Path, llvm_bin: Path, no_lto: bool = False) -> str:
    """Rewrite upstream's hard-coded system paths and toolchain assumptions.
    Every anchor must match exactly once, so upstream drift fails loudly."""
    p = src
    # 1-5: SDK / VC9 locations -> the administrative-install extraction under tools/sdk/ext
    p = _patch(p, r"rf'C:\Program Files (x86)\Microsoft SDKs\Windows\v{SDK_VERSION}\Include'", f"r'{SDK_DIR}\\Include'")
    p = _patch(p, r"rf'C:\Program Files (x86)\Microsoft SDKs\Windows\v{SDK_VERSION}\Lib'", f"r'{SDK_DIR}\\Lib'")
    p = _patch(p, r"rf'C:\Program Files (x86)\Microsoft Visual Studio 9.0\VC\include'", f"r'{VC9_DIR}\\include'")
    p = _patch(p, r"sdk_path = rf'C:\Program Files (x86)\Microsoft SDKs\Windows\v{sdk_version}'", f"sdk_path = r'{SDK_DIR}'")
    p = _patch(p, r"vs_path = r'C:\Program Files (x86)\Microsoft Visual Studio 9.0\VC'", f"vs_path = r'{VC9_DIR}'")
    # 6: keep VC9\lib on the link path (upstream relies on the LIB env var for it)
    p = _patch(p, "LIB_PATHS = [\n", f"LIB_PATHS = [\n    r'{VC9_DIR}\\lib',\n")
    # 7: upstream shells out to update_commit_id.bat, which cmd cannot resolve from this
    #    environment; commit_id.inc is generated by write_commit_id() instead.
    p = _patch(p, "    update_commit_id(log)\n", "    pass  # commit_id.inc written by build_dll.py\n")
    major = clang_major(llvm_bin)
    extra = []
    # 7b: LLVM 16-19 reject casting MAX_CIV_PLAYERS (63) to PlayerTypes in a constant expression
    #     (CvUnit.cpp: GET_PLAYER(BARBARIAN_PLAYER)) as error-by-default; it is a warning they allow
    #     turning off, and the value is valid at run time.
    if major and major < 20:
        extra.append("'-Wno-enum-constexpr-conversion'")
    # 8: target the Visual C++ 2008 runtime explicitly. Upstream CI puts VC9's cl.exe on PATH, which clang-cl
    #    reads to pick -fms-compatibility-version=15.00; with no VC9 compiler installed, clang-cl assumes a
    #    modern runtime and emits magic-static guards (__Init_thread_*), sized deallocation, __std_terminate
    #    and TLS initialisation the game's VC9 CRT does not provide. A DLL built that way, with those
    #    features patched out by hand, linked but failed to initialise in the game (error 1114).
    extra.append("'-fms-compatibility-version=15.00.30729'")
    if no_lto:
        p = _patch(p, "        args.append('-flto')\n", "        pass  # -flto removed by build_dll.py --no-lto\n")
    if extra:
        p = _patch(p, "args = ['-m32', '-msse3', '/c',",
                   "args = ['-m32', '-msse3', " + ", ".join(extra) + ", '/c',")
    return p


def clang_major(llvm_bin: Path) -> int:
    import re
    import subprocess
    out = subprocess.run([str(llvm_bin / "clang-cl.exe"), "--version"], capture_output=True, text=True).stdout
    m = re.search(r"clang version (\d+)", out)
    return int(m.group(1)) if m else 0


if __name__ == "__main__":
    sys.exit(main())
